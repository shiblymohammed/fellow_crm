export default function AgencySidebar() {
  const pathname = usePathname();
  const router = useRouter();
  const [isCollapsed, setIsCollapsed] = useState(false);
  const user = useAuthStore(state => state.user);

  const [isPending, startTransition] = useTransition();
  const [pendingHref, setPendingHref] = useState<string | null>(null);

  useEffect(() => {
    setPendingHref(null);
  }, [pathname]);

  const handleNavigation = (e: React.MouseEvent<HTMLAnchorElement>, href: string) => {
    e.preventDefault();
    if (pathname === href) return;
    setPendingHref(href);
    startTransition(() => {
      router.push(href);
    });
  };

  return (
    <aside
      className={`relative bg-[#0d1117] border-r border-gray-800 text-gray-300 flex flex-col transition-all duration-300 ease-in-out shrink-0 ${
        isCollapsed ? 'w-20' : 'w-64'
      }`}
    >
      {/* Brand Header */}
      <div className="h-16 flex items-center justify-between px-5 border-b border-gray-800">
        {!isCollapsed ? (
          <Link href="/dashboard" className="flex items-center gap-2 overflow-hidden whitespace-nowrap group">
            <div className="w-8 h-8 rounded-xl bg-gradient-to-tr from-primary to-orange-400 flex items-center justify-center text-white font-extrabold text-sm shadow-md group-hover:scale-105 transition-transform">
              F
            </div>
            <span className="text-xl font-heading font-bold text-white tracking-tight">
              Fellow<span className="text-primary font-black">CRM</span>
            </span>
          </Link>
        ) : (
          <Link href="/dashboard" className="w-full flex justify-center text-primary font-black text-xl">
            F
          </Link>
        )}
      </div>

      {/* Agency Pill Badge */}
      {!isCollapsed && (
        <div className="px-5 py-3 border-b border-gray-800/60 bg-white/[0.02]">
          <div className="flex items-center gap-2">
            <span className="w-2 h-2 rounded-full bg-emerald-400 animate-pulse"></span>
            <span className="text-xs font-semibold text-gray-400 truncate uppercase tracking-wider">
              {user?.tenantSlug?.replace('-', ' ') || 'Agency Workspace'}
            </span>
          </div>
        </div>
      )}

      {/* Navigation */}
      <nav className="flex-1 overflow-y-auto py-4 px-3 space-y-1 scrollbar-hide">
        {!isCollapsed && (
          <div className="px-3 mb-2 text-[11px] font-bold text-gray-500 uppercase tracking-wider">
            Main Menu
          </div>
        )}

        {agencyNavItems.map(item => {
          const isActive =
            item.href === '/dashboard'
              ? pathname === '/dashboard'
              : pathname.startsWith(item.href);
              
          const isNavigatingHere = isPending && pendingHref === item.href;
          const displayActive = isActive || isNavigatingHere;

          return (
            <Link
              key={item.href}
              href={item.href}
              prefetch={false}
              onClick={(e) => handleNavigation(e, item.href)}
              className={`
                group flex items-center gap-3 px-3 py-2.5 rounded-xl font-medium transition-all text-sm relative overflow-hidden
                ${
                  displayActive
                    ? 'bg-primary text-white font-semibold shadow-lg shadow-primary/25'
                    : 'text-gray-400 hover:text-white hover:bg-white/5'
                }
              `}
              title={isCollapsed ? item.name : undefined}
            >
              <div
                className={`
                flex items-center justify-center transition-colors shrink-0
                ${displayActive ? 'text-white' : 'text-gray-400 group-hover:text-white'}
              `}
              >
                {item.icon}
              </div>
              {!isCollapsed && (
                <div className="flex-1 flex items-center justify-between overflow-hidden">
                  <span className="whitespace-nowrap truncate">{item.name}</span>
                  <div className="flex items-center gap-2">
                    {isNavigatingHere && (
                      <svg className="animate-spin h-3.5 w-3.5 text-white" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24">
                        <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4"></circle>
                        <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
                      </svg>
                    )}
                    {item.badge && !isNavigatingHere && (
                      <span className="text-[10px] font-extrabold uppercase tracking-wider px-1.5 py-0.5 rounded bg-white/15 text-white/90">
                        {item.badge}
                      </span>
                    )}
                  </div>
                </div>
              )}
            </Link>
          );
        })}
      </nav>

      {/* Collapse Toggle */}
      <div className="p-3 border-t border-gray-800">
        <button
          onClick={() => setIsCollapsed(!isCollapsed)}
          className="w-full flex items-center justify-center gap-2 p-2 rounded-xl text-gray-400 hover:text-white hover:bg-white/5 transition-colors text-sm font-medium"
        >
          {isCollapsed ? (
            <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={2} stroke="currentColor" className="w-5 h-5">
              <path strokeLinecap="round" strokeLinejoin="round" d="m5.25 4.5 7.5 7.5-7.5 7.5m6-15 7.5 7.5-7.5 7.5" />
            </svg>
          ) : (
            <>
              <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={2} stroke="currentColor" className="w-5 h-5">
                <path strokeLinecap="round" strokeLinejoin="round" d="m18.75 4.5-7.5 7.5 7.5 7.5m-6-15L5.25 12l7.5 7.5" />
              </svg>
              <span className="text-xs">Collapse</span>
            </>
          )}
        </button>
      </div>
    </aside>
  );
}
